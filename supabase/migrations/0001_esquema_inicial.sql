-- ---------- perfiles (extiende auth.users) ----------
create table if not exists public.perfiles (
    id         uuid primary key references auth.users (id) on delete cascade,
    nombre     text,
    rol        text not null default 'estudiante'
               constraint perfiles_rol_check check (rol in ('estudiante', 'docente', 'admin')),
    foto_url   text,
    creado_en  timestamptz not null default now()
);

-- ---------- cohortes ----------
create table if not exists public.cohortes (
    id      bigint generated by default as identity primary key,
    nombre  text not null,
    numero  integer not null unique
);

-- ---------- laboratorios ----------
create table if not exists public.laboratorios (
    id           bigint generated by default as identity primary key,
    cohorte_id   bigint not null references public.cohortes (id) on delete cascade,
    codigo       text not null unique,
    titulo       text not null,
    descripcion  text,
    objetivos    text
);
create index if not exists ix_laboratorios_cohorte_id on public.laboratorios (cohorte_id);

-- ---------- rubricas (una por laboratorio) ----------
create table if not exists public.rubricas (
    id              bigint generated by default as identity primary key,
    laboratorio_id  bigint not null unique references public.laboratorios (id) on delete cascade
);

-- ---------- rubrica_versiones (inmutables al aprobarse) ----------
create table if not exists public.rubrica_versiones (
    id          bigint generated by default as identity primary key,
    rubrica_id  bigint not null references public.rubricas (id) on delete cascade,
    version     integer not null,
    contenido   jsonb not null,
    estado      text not null default 'borrador'
                constraint rubrica_versiones_estado_check check (estado in ('borrador', 'aprobada')),
    creada_por  uuid references public.perfiles (id) on delete set null,
    creada_en   timestamptz not null default now(),
    constraint rubrica_versiones_rubrica_version_key unique (rubrica_id, version)
);
create index if not exists ix_rubrica_versiones_rubrica_id on public.rubrica_versiones (rubrica_id);
create index if not exists ix_rubrica_versiones_creada_por on public.rubrica_versiones (creada_por);

-- ---------- entregas ----------
create table if not exists public.entregas (
    id                  bigint generated by default as identity primary key,
    estudiante_id       uuid not null references public.perfiles (id) on delete cascade,
    laboratorio_id      bigint not null references public.laboratorios (id) on delete cascade,
    rubrica_version_id  bigint not null references public.rubrica_versiones (id) on delete restrict,
    pdf_path            text not null,
    codigo_zip_path     text,
    github_url          text,
    extras              jsonb,
    creada_en           timestamptz not null default now()
);
create index if not exists ix_entregas_estudiante_id on public.entregas (estudiante_id);
create index if not exists ix_entregas_laboratorio_id on public.entregas (laboratorio_id);
create index if not exists ix_entregas_rubrica_version_id on public.entregas (rubrica_version_id);

-- ---------- evaluaciones ----------
create table if not exists public.evaluaciones (
    id               bigint generated by default as identity primary key,
    entrega_id       bigint not null references public.entregas (id) on delete cascade,
    estado           text not null default 'borrador'
                     constraint evaluaciones_estado_check
                     check (estado in ('borrador', 'en_revision', 'aprobada', 'publicada', 'error')),
    nota             numeric(2, 1)
                     constraint evaluaciones_nota_check check (nota is null or (nota >= 0 and nota <= 5)),
    proveedor        text,
    modelo           text,
    prompt_version   text,
    temperatura      double precision,
    respuesta_cruda  jsonb,
    resultado        jsonb,
    error            text,
    creada_en        timestamptz not null default now(),
    aprobada_por     uuid references public.perfiles (id) on delete set null,
    aprobada_en      timestamptz,
    publicada_en     timestamptz
);
create index if not exists ix_evaluaciones_entrega_id on public.evaluaciones (entrega_id);
create index if not exists ix_evaluaciones_aprobada_por on public.evaluaciones (aprobada_por);

-- ---------- evaluacion_criterios ----------
create table if not exists public.evaluacion_criterios (
    id                      bigint generated by default as identity primary key,
    evaluacion_id           bigint not null references public.evaluaciones (id) on delete cascade,
    criterio_id             text not null,
    nivel_ia                text,
    nivel_final             text,
    puntaje_normalizado     double precision,
    evidencias              jsonb,
    evidencias_verificadas  jsonb,
    justificacion           text,
    ajuste_docente          text,
    constraint evaluacion_criterios_evaluacion_criterio_key unique (evaluacion_id, criterio_id)
);
create index if not exists ix_evaluacion_criterios_evaluacion_id
    on public.evaluacion_criterios (evaluacion_id);

-- ---------- verificaciones_codigo (una por evaluación) ----------
create table if not exists public.verificaciones_codigo (
    id             bigint generated by default as identity primary key,
    evaluacion_id  bigint not null unique references public.evaluaciones (id) on delete cascade,
    sintaxis       jsonb,
    ruff           jsonb,
    complejidad    jsonb,
    tests          jsonb,
    metricas       jsonb,
    sandbox        text
);

-- ---------- auditoria ----------
create table if not exists public.auditoria (
    id          bigint generated by default as identity primary key,
    usuario_id  uuid references public.perfiles (id) on delete set null,
    entidad     text not null,
    entidad_id  text not null,
    accion      text not null,
    antes       jsonb,
    despues     jsonb,
    motivo      text,
    creado_en   timestamptz not null default now()
);
create index if not exists ix_auditoria_usuario_id on public.auditoria (usuario_id);
create index if not exists ix_auditoria_entidad on public.auditoria (entidad, entidad_id);

-- ---------- tematicas (taxonomía del mapa mental) ----------
create table if not exists public.tematicas (
    id           bigint generated by default as identity primary key,
    nombre       text not null unique,
    padre_id     bigint references public.tematicas (id) on delete set null,
    descripcion  text
);
create index if not exists ix_tematicas_padre_id on public.tematicas (padre_id);

-- ---------- config_ia (una sola fila, id = 1) ----------
create table if not exists public.config_ia (
    id               integer primary key default 1 constraint config_ia_una_fila check (id = 1),
    proveedor        text not null,
    modelo           text not null,
    temperatura      double precision not null
                     constraint config_ia_temperatura_check check (temperatura >= 0 and temperatura <= 0.2),
    actualizado_por  uuid references public.perfiles (id) on delete set null,
    actualizado_en   timestamptz not null default now()
);

-- =====================================================================
-- Trigger RF-01 CA2: al registrarse un usuario en auth.users se crea su
-- perfil con rol 'estudiante'. El nombre se toma de raw_user_meta_data.nombre
-- (si el frontend lo envía en signUp) o, si no, del email.
-- =====================================================================
create or replace function public.crear_perfil_nuevo_usuario()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.perfiles (id, nombre, rol)
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'nombre', new.email),
        'estudiante'
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists al_crear_usuario on auth.users;
create trigger al_crear_usuario
    after insert on auth.users
    for each row execute function public.crear_perfil_nuevo_usuario();

