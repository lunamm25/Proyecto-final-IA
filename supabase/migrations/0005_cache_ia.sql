-- =====================================================================
-- 0005 · Caché de resultados de IA (RF-08 CA3 y RF-09 CA2)
-- Evita llamar al LLM en cada consulta del informe o del mapa:
--   tipo = 'informe_narrativo' → clave = id del estudiante (uuid en texto)
--   tipo = 'mapeo_tematicas'   → clave = id de la versión de rúbrica
-- huella: hash SHA-256 de los datos que se enviaron a la IA (números del
--   informe, o lista de temáticas para el mapeo). Si la huella o la versión
--   del prompt cambian, el backend vuelve a generar y reemplaza la fila.
-- contenido: solo la salida ya validada y traducida por el backend
--   (sin respuestas crudas: esas quedan en auditoria).
-- Los números del informe NO se guardan aquí: se recalculan siempre.
-- Idempotente: se puede ejecutar varias veces sin error.
-- =====================================================================

create table if not exists public.cache_ia (
    id              bigint generated by default as identity primary key,
    tipo            text not null
                    constraint cache_ia_tipo_check
                    check (tipo in ('informe_narrativo', 'mapeo_tematicas')),
    clave           text not null,
    huella          text not null,
    prompt_version  text,
    proveedor       text,
    modelo          text,
    contenido       jsonb not null,
    generado_en     timestamptz not null default now(),
    constraint cache_ia_tipo_clave_key unique (tipo, clave)
);

-- Igual que el resto de tablas: solo el backend accede (RLS sin políticas).
alter table public.cache_ia enable row level security;
